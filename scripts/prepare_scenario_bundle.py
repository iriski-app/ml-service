"""Package the existing scenario CatBoost and its independent validation report.

--enable enables only the declared synthetic formula analysis. It is not an
approval of market forecasting accuracy. Without a report, packaging stays disabled.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import shutil
from pathlib import Path


def package(model_file: Path, output_dir: Path, version: str, *,
            validation_report: Path | None = None, enable: bool = False) -> None:
    if not model_file.is_file() or not version.strip():
        raise ValueError("model file and version are required")
    report = None
    if validation_report is not None:
        report = json.loads(validation_report.read_text(encoding="utf-8"))
    if enable:
        if report is None or report.get("features") != ["shock_abs", "DurationMod", "YIELDCLOSE", "FACEVALUE"]:
            raise ValueError("a matching validation report is required to enable the artifact")
        if report.get("model_sha256") != hashlib.sha256(model_file.read_bytes()).hexdigest():
            raise ValueError("validation report does not belong to this model artifact")
        splits = [set(report["splits"][name]["bonds"]) for name in ("train", "validation", "test")]
        if (not all(splits) or any(splits[i] & splits[j] for i, j in [(0, 1), (0, 2), (1, 2)])
                or not math.isfinite(float(report["test_mae_rub_for_10_face_values"]))):
            raise ValueError("validation report must contain disjoint bond splits and a finite test error")
        if set(report.get("input_ranges", {})) != {"duration_mod", "ytm", "face_value"}:
            raise ValueError("validation report must define the training domain")
    output_dir.mkdir(parents=True, exist_ok=True)
    target = output_dir / "scenario.cbm"
    if model_file.resolve() != target.resolve():
        shutil.copyfile(model_file, target)
    metadata = {
        "model_version": version,
        "model_file": target.name,
        "sha256": {target.name: hashlib.sha256(target.read_bytes()).hexdigest()},
        "features": ["shock_abs", "DurationMod", "YIELDCLOSE", "FACEVALUE"],
        "target_kind": "formula_proxy_reference_position",
        "target_unit": "RUB_FOR_10_FACE_VALUES",
        "shift_bp_min": -200,
        "shift_bp_max": 200,
        "enabled_for_service": enable,
        "experimental": True,
        "limitations": [
            "Target was generated by the duration-convexity formula for ten face values.",
            "This is not a market-price forecast or a prediction for the actual basket.",
            "The model supports RUB face values only; actual quantity, trade side and FX are not inputs.",
            "Convexity in the training target is a maturity/yield approximation, not the position's convexity.",
            "A zero yield shift returns exactly zero by the target formula.",
        ],
    }
    if report is not None:
        target_report = output_dir / "training_report.json"
        if validation_report.resolve() != target_report.resolve():
            shutil.copyfile(validation_report, target_report)
        metadata.update({"input_ranges": report["input_ranges"],
                         "tested_shifts_bp": report["tested_shifts_bp"],
                         "training_report_file": target_report.name})
        metadata["sha256"][target_report.name] = hashlib.sha256(target_report.read_bytes()).hexdigest()
        metadata["limitations"].append("Test error is measured on held-out bonds at overlapping dates, not future market prices.")
    (output_dir / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-file", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--validation-report", type=Path)
    parser.add_argument("--enable", action="store_true", help="Enable the declared formula analysis with a validation report")
    arguments = parser.parse_args()
    package(arguments.model_file, arguments.output_dir, arguments.version,
            validation_report=arguments.validation_report, enable=arguments.enable)
